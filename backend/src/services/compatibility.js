// Patient blood type -> donor types that can give red cells to them
const COMPATIBLE_DONORS = {
  'O-':  ['O-'],
  'O+':  ['O-', 'O+'],
  'A-':  ['O-', 'A-'],
  'A+':  ['O-', 'O+', 'A-', 'A+'],
  'B-':  ['O-', 'B-'],
  'B+':  ['O-', 'O+', 'B-', 'B+'],
  'AB-': ['O-', 'A-', 'B-', 'AB-'],
  'AB+': ['O-', 'O+', 'A-', 'A+', 'B-', 'B+', 'AB-', 'AB+'],
};

export function compatibleDonorTypes(patientType) {
  const types = COMPATIBLE_DONORS[patientType];
  if (!types) throw new Error(`Unknown blood type: ${patientType}`);
  return types;
}